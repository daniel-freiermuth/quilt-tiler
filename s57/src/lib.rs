#[derive(Debug, Clone)]
pub enum AttrValue {
    Int(u32),
    Double(f64),
    Str(String),
}

#[derive(Debug, Clone)]
pub struct Attribute {
    pub code: u16,
    pub value: AttrValue,
}

#[derive(Debug, Clone)]
pub enum Geometry {
    None,
    Point(Point),
    Soundings(Vec<(Point, f64)>), // (position, depth)
    Line(LineString),             // single stroke (sequence of vertices)
    Area(Polygon),
}

#[derive(Debug, Clone)]
pub struct Feature {
    pub type_code: u16,
    pub attributes: Vec<Attribute>,
    pub geometry: Geometry,
}

// ── Cell ─────────────────────────────────────────────────────────────────────

/// A parsed S-57 navigational chart cell ready for tile encoding.
///
/// Common intermediate type between chart parsers (OESU, native S-57, …)
/// and consumers (tile writer, style generator, …).  Parsers produce it;
/// consumers read it.
#[derive(Debug)]
pub struct S57Cell {
    pub name: String,
    pub native_scale: u32,
    /// Geographic bounds `[west, south, east, north]` in WGS84 degrees.
    pub bounds: [f64; 4],
    pub features: Vec<Feature>,
    /// Coverage polygons in WGS84 `[lon, lat]` order.  A cell may have
    /// multiple disjoint coverage areas (outer `Vec`); each ring is a
    /// closed polygon (inner `Vec`).  Empty when no COVR record was present.
    pub coverage: MultiPolygon,
    pub source: String,
    /// Most recent edition/update date — `HEADER_CELL_UPDATEDATE` if the
    /// cell has updates applied, else `HEADER_CELL_PUBLISHDATE`.
    /// [`EditionDate::unknown`] if neither header was present. Consumed by
    /// `quilt_tiler::tile_source::TileSource::tiebreak` to rank otherwise
    /// equally-zoom-fit tile candidates — not a general identity/ordering
    /// for this type, so `S57Cell` deliberately has no `Eq`/`Ord` impl.
    pub edition_date: EditionDate,
}

