#[must_use]
pub fn object_acronym(code: u16) -> Option<&'static str> {
    OBJECT_CLASSES
        .iter()
        .find(|(c, _)| *c == code)
        .map(|(_, a)| *a)
}

#[must_use]
pub fn attribute_acronym(code: u16) -> Option<&'static str> {
    ATTRIBUTES
        .iter()
        .find(|(c, ..)| *c == code)
        .map(|(_, a, _)| *a)
}

/// Object-class code for an acronym such as `"DEPARE"`.
#[must_use]
pub fn object_code(acronym: &str) -> Option<u16> {
    OBJECT_CLASSES
        .iter()
        .find(|(_, a)| *a == acronym)
        .map(|(c, _)| *c)
}

/// Attribute code and catalogue type for an acronym such as `"DRVAL1"`.
#[must_use]
pub fn attribute(acronym: &str) -> Option<(u16, AttrType)> {
    ATTRIBUTES
        .iter()
        .find(|(_, a, _)| *a == acronym)
        .map(|&(c, _, t)| (c, t))
}
